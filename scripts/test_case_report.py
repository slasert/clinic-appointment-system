"""Builds docs/test-results/test-case-results.md from the test sources and the Surefire XML reports.

Run after `mvnw clean test`:  python scripts/test_case_report.py
- techniques come from the @Tag annotations in the source,
- the actual result (PASS/FAIL per invocation) comes from target/surefire-reports/*.xml.
"""
import glob
import io
import os
import re
import xml.etree.ElementTree as ET
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TC = re.compile(r"TC-[A-Z]+-\d+")

# ---- 1. test case catalogue from source: ID -> (title, class, techniques)
catalogue = {}
for path in sorted(glob.glob(os.path.join(ROOT, "src", "test", "java", "**", "*Test.java"), recursive=True)):
    cls = os.path.splitext(os.path.basename(path))[0]
    tags, title = [], None
    for line in io.open(path, encoding="utf-8"):
        line = line.strip()
        m = re.match(r'@(?:DisplayName|ParameterizedTest)\(\s*(?:name\s*=\s*)?"(.*)"\)', line)
        if m and TC.search(m.group(1)):
            title = m.group(1)
        t = re.match(r'@Tag\("(\w+)"\)', line)
        if t:
            tags.append(t.group(1))
        if re.match(r"(public |private |protected )?void \w+\(", line):
            if title:
                tc_id = TC.search(title).group(0)
                text = title.replace(tc_id, "").strip()
                catalogue[tc_id] = (text, cls, tags or ["Functional"])
            tags, title = [], None

# ---- 2. actual results from Surefire XML
results = defaultdict(lambda: [0, 0])  # id -> [passed, failed]
for path in glob.glob(os.path.join(ROOT, "target", "surefire-reports", "TEST-*.xml")):
    for case in ET.parse(path).getroot().iter("testcase"):
        m = TC.search(case.get("name", ""))
        if not m:
            continue
        failed = case.find("failure") is not None or case.find("error") is not None
        results[m.group(0)][1 if failed else 0] += 1

# ---- 3. markdown
def sort_key(tc_id):
    prefix, num = tc_id.rsplit("-", 1)
    return prefix, int(num)

rows, techniques = [], Counter()
for tc_id in sorted(catalogue, key=sort_key):
    text, cls, tags = catalogue[tc_id]
    passed, failed = results.get(tc_id, [0, 0])
    actual = "NOT RUN" if passed + failed == 0 else ("FAIL" if failed else "PASS")
    techniques.update(tags)
    rows.append(f"| {tc_id} | {text.replace('|', '/')} | {cls} | {', '.join(tags)} | {passed + failed} | {actual} |")

total_pass = sum(r[0] for r in results.values())
total_fail = sum(r[1] for r in results.values())
out = [
    "# Test case results",
    "",
    "Generated by `scripts/test_case_report.py` from the test sources and `target/surefire-reports` "
    "after `mvnw clean test`. The test name states the input and the expected result; "
    "*Actual* is the outcome recorded by Surefire for every invocation of that test case.",
    "",
    f"- Test cases: {len(rows)}",
    f"- JUnit invocations: {total_pass + total_fail} (passed {total_pass}, failed {total_fail})",
    "- Test cases per technique tag: " + ", ".join(f"{k} {v}" for k, v in sorted(techniques.items())),
    "",
    "| ID | Test (input → expected result) | Class | Technique | Runs | Actual |",
    "|---|---|---|---|---|---|",
    *rows,
]
target = os.path.join(ROOT, "docs", "test-results", "test-case-results.md")
io.open(target, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"{len(rows)} test cases, {total_pass} passed / {total_fail} failed invocations -> {target}")
